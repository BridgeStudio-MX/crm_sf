const lastDayOfMonth = (mesAnio: string): string => {
  const [yearText, monthText] = mesAnio.split('-');
  const year = Number(yearText);
  const month = Number(monthText);
  const date = new Date(Date.UTC(year, month, 0));

  return date.toISOString().slice(0, 10);
};

export const ceoDashboardStore = {
  listSnapshots: (): CeoMonthlySnapshot[] =>
    SNAPSHOT_SEED.map((snapshot) => ({
      ...snapshot,
      fechaSnapshot: lastDayOfMonth(snapshot.mesAnio),
    })),

  getLatestSnapshot: (): CeoMonthlySnapshot => {
    const snapshots = ceoDashboardStore.listSnapshots();
    return snapshots[snapshots.length - 1];
  },

  getPreviousSnapshot: (): CeoMonthlySnapshot | undefined => {
    const snapshots = ceoDashboardStore.listSnapshots();
    return snapshots.length > 1 ? snapshots[snapshots.length - 2] : undefined;
  },
};
